def generate(feature_dir):
    dashboard = feature_dir / "dashboard.html"
    tasks = load_tasks(feature_dir)
    if not tasks:
        if dashboard.exists():
            if MARKER not in dashboard.read_text(encoding="utf-8"):
                raise ValueError(f"{dashboard}: refusing to remove a page not generated by this skill")
            dashboard.unlink()
        return "omitted"
    if dashboard.is_symlink():
        raise ValueError(f"{dashboard}: refusing to overwrite a symlink")
    if dashboard.exists() and MARKER not in dashboard.read_text(encoding="utf-8"):
        raise ValueError(f"{dashboard}: refusing to overwrite a page not generated by this skill")
    project_name, feature_id, feature_title = read_feature_metadata(feature_dir)
    dashboard.write_text(render_html(tasks, project_name, feature_id, feature_title), encoding="utf-8")
    return f"generated with {len(tasks)} tasks"


def main():
    if len(sys.argv) != 2:
        print("Usage: generate_dashboard.py <feature-folder>", file=sys.stderr)
        return 2
    feature_dir = Path(sys.argv[1]).resolve()
    try:
        print(generate(feature_dir))
    except (OSError, ValueError) as error:
        print(f"dashboard generation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
