def scalar(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def read_task(readme):
    text = readme.read_text(encoding="utf-8")
    match = re.match(r"\A---\s*\n(.*?)\n---(?:\n|$)", text, re.S)
    if not match:
        raise ValueError(f"{readme}: missing YAML frontmatter")
    fields = {}
    lines = match.group(1).splitlines()
    for index, line in enumerate(lines):
        field = re.match(r"^(id|title|status|depends_on):\s*(.*)$", line)
        if not field:
            continue
        key, value = field.groups()
        if key != "depends_on":
            fields[key] = scalar(value)
            continue
        if value.startswith("[") and value.endswith("]"):
            inner = value[1:-1].strip()
            fields[key] = [scalar(part) for part in inner.split(",") if part.strip()]
        elif value:
            raise ValueError(f"{readme}: depends_on must be [] or a YAML list")
        else:
            dependencies = []
            for item in lines[index + 1 :]:
                if not item.strip():
                    continue
                list_item = re.match(r"^\s+-\s+(.+?)\s*$", item)
                if list_item:
                    dependencies.append(scalar(list_item.group(1)))
                elif not item.startswith(" "):
                    break
            fields[key] = dependencies
    missing = [key for key in ("id", "title", "status", "depends_on") if key not in fields]
    if missing:
        raise ValueError(f"{readme}: missing frontmatter fields: {', '.join(missing)}")
    return fields


def read_handoffs(handoffs_dir, task):
    if not handoffs_dir.is_dir():
        return []
    candidates = []
    for path in handoffs_dir.glob("*.md"):
        match = HANDOFF_NAME.match(path.name)
        if path.is_file() and not path.is_symlink():
            if not match:
                warnings.warn(f"Noncanonical handoff filename: {path}", RuntimeWarning)
            candidates.append((
                match.group(1) if match else "",
                int(match.group("sequence")) if match else 0,
                path,
                match.group("role") if match else "",
            ))
    handoffs = []
    for stamp, sequence, path, name_role in candidates:
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as error:
            warnings.warn(f"Unable to read handoff file {path}: {error}", RuntimeWarning)
            continue
        metadata = {}
        verdict = ""
        for line in text.splitlines():
            match = HANDOFF_FIELD.match(line)
            if match:
                metadata[match.group(1).lower()] = scalar(match.group(2))
            verdict_match = HANDOFF_VERDICT.match(line)
            if verdict_match:
                verdict = scalar(verdict_match.group(1))
        summary_match = re.search(r"^## Summary\s*\n(.*?)(?=^## |\Z)", text, re.M | re.S)
        if summary_match:
            summary_text = summary_match.group(1)
        else:
            summary_match = re.search(
                r"^\s*\*\*Summary(?::\*\*|\*\*)\s*:?\s*(.*?)(?=^\s*\*\*[^*]+\*\*\s*:|\n\s*\n|\Z)",
                text,
                re.I | re.M | re.S,
            )
            summary_text = summary_match.group(1) if summary_match else ""
        summary = " ".join(line.strip() for line in summary_text.splitlines() if line.strip())
        if not any(metadata.values()) and not verdict and not summary:
            warnings.warn(f"Unrecognized handoff content: {path}", RuntimeWarning)
        filename_timestamp = (
            f"{stamp[:4]}-{stamp[4:6]}-{stamp[6:8]}T{stamp[9:11]}:{stamp[11:13]}:{stamp[13:15]}Z"
            if stamp else ""
        )
        name_role_text = name_role.replace("-", " ").title() if name_role else "Unknown"
        role = metadata.get("role") or metadata.get("from") or name_role_text
        role_key = role.strip().lower().replace(" ", "-")
        recipient = metadata.get("recipient") or metadata.get("to", "")
        if recipient.strip().lower() in {"", "—", "-", "none", "null", "unknown", "n/a", "not recorded"}:
            recipient = "project-manager" if role_key in {"worker", "reviewer"} else ""
        outcome = metadata.get("outcome") or metadata.get("decision") or verdict
        if outcome.strip().upper() == "APPROVED":
            outcome = "approved"
        elif outcome.strip().upper() == "CHANGES_REQUESTED":
            outcome = "changes_requested"
        if outcome.strip().lower() in {"", "—", "-", "none", "null", "unknown", "n/a", "not recorded"}:
            outcome = "Handoff"
        body_timestamp = next((value for key, value in metadata.items() if key == "created" or key.startswith("timestamp")), "")
        timestamp = parse_handoff_timestamp(body_timestamp) or filename_timestamp
        sort_timestamp = sortable_handoff_timestamp(timestamp)
        handoffs.append({
            "task_id": task["id"],
            "task_title": task["title"],
            "role": role,
            "recipient": recipient,
            "outcome": outcome,
            "verdict": verdict,
            "timestamp": timestamp,
            "summary": summary,
            "content": text,
            "filename": path.name,
            "sort_timestamp": sort_timestamp,
            "sequence": sequence,
        })
    return handoffs


def parse_handoff_timestamp(value):
    value = value.strip()
    if not value:
        return ""
    value = re.sub(
        r"\s*\(UTC([+-])(\d{1,2})(?::?(\d{2}))?\)$",
        lambda match: f"{match.group(1)}{int(match.group(2)):02d}:{match.group(3) or '00'}",
        value,
    )
    value = value.replace("Z", "+00:00")
    value = re.sub(r"\s+UTC$", "+00:00", value, flags=re.I)
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError:
        return ""
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.isoformat(timespec="seconds").replace("+00:00", "Z")


def sortable_handoff_timestamp(value):
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return ""
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def html_safe_json(value):
    """Serialize JSON so its contents cannot terminate an HTML script element."""
    return (
        json.dumps(value, ensure_ascii=True, separators=(",", ":"))
        .replace("&", "\\u0026")
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
    )


def latest_handoff(handoffs):
    if not handoffs:
        return {"role": "—", "recipient": "", "outcome": "No handoff yet", "timestamp": "—", "sort_timestamp": "", "summary": ""}
    latest = max(handoffs, key=lambda item: (item["sort_timestamp"], item["sequence"], item["filename"]))
    return {key: latest[key] for key in ("role", "recipient", "outcome", "timestamp", "sort_timestamp", "summary")}


def sort_done_tasks(tasks):
    done = [task for task in tasks if task["status"] == "done"]
    done.sort(key=lambda task: task["id"])
    done.sort(key=lambda task: task["latest_handoff"].get("sort_timestamp", ""), reverse=True)
    done = iter(done)
    return [next(done) if task["status"] == "done" else task for task in tasks]


def format_duration(seconds):
    seconds = max(0, int(seconds))
    if seconds < 60:
        return f"{seconds}s"
    minutes, _ = divmod(seconds, 60)
    days, minutes = divmod(minutes, 1440)
    hours, minutes = divmod(minutes, 60)
    return " ".join(f"{value}{unit}" for value, unit in ((days, "d"), (hours, "h"), (minutes, "m")) if value)


def task_cycle_time(task, generated_at):
    handoffs = task.get("handoffs", [])
    dispatches = [handoff for handoff in handoffs if handoff["role"].strip().lower().replace(" ", "-") == "project-manager" and handoff["recipient"].strip().lower() == "worker"]
    if not dispatches:
        return {"seconds": None, "label": "Not started"}
    dispatches.sort(key=lambda item: (item["sort_timestamp"], item["sequence"], item["filename"]))
    start = dispatches[0]["sort_timestamp"]
    if not start:
        return {"seconds": None, "label": "Time unavailable"}
    if task["status"] == "done":
        approvals = [handoff for handoff in handoffs if handoff["role"].strip().lower().replace(" ", "-") == "reviewer" and (handoff["outcome"].strip().lower().startswith("approved") or handoff.get("verdict", "").strip().lower() == "approved") and handoff["sort_timestamp"]]
        if not approvals:
            return {"seconds": None, "label": "Time unavailable"}
        end = max(approvals, key=lambda item: (item["sort_timestamp"], item["sequence"], item["filename"]))["sort_timestamp"]
    else:
        end = generated_at
    start_dt = datetime.fromisoformat(start.replace("Z", "+00:00"))
    end_dt = datetime.fromisoformat(end.replace("Z", "+00:00"))
    if end_dt < start_dt:
        return {"seconds": None, "label": "Time unavailable"}
    seconds = int((end_dt - start_dt).total_seconds())
    label = format_duration(seconds) + (" (ongoing)" if task["status"] != "done" else "")
    return {"seconds": seconds, "label": label}


def current_owner(status, handoff):
    if status == "done":
        return "Completed"
    if status == "blocked":
        return "Human"
    recipient = handoff.get("recipient", "").strip()
    if recipient.lower() not in {"", "—", "-", "none", "null", "unknown", "n/a"}:
        aliases = {"project-manager": "Project manager", "reviewer": "Reviewer", "worker": "Worker", "human": "Human"}
        return aliases.get(recipient.lower(), recipient.replace("-", " ").title())
    fallbacks = {"blocked": "Human", "needs_human": "Human", "waiting_human": "Human", "review": "Reviewer", "in_progress": "Worker"}
    return fallbacks.get(status, "Project manager")


def kanban_lane(status):
    if status in {"in_progress", "changes_requested"}:
        return "Worker"
    if status in {"review", "blocked"}:
        return "Reviewer"
    if status == "done":
        return "Done"
    return "Project manager"


def load_tasks(feature_dir):
    tasks_dir = feature_dir / "tasks"
    if not tasks_dir.is_dir():
        raise ValueError(f"{tasks_dir}: task directory does not exist")
    tasks = []
    for path in sorted(tasks_dir.glob("T-*")):
        if not (path / "README.md").is_file():
            continue
        task = read_task(path / "README.md")
        task["content"] = (path / "README.md").read_text(encoding="utf-8")
        task["handoffs"] = read_handoffs(path / "handoffs", task)
        task["latest_handoff"] = latest_handoff(task["handoffs"])
        task["owner"] = current_owner(task["status"], task["latest_handoff"])
        task["lane"] = kanban_lane(task["status"])
        tasks.append(task)
    if not tasks:
        return []
    by_id = {task["id"]: task for task in tasks}
    if len(by_id) != len(tasks):
        raise ValueError("task IDs must be unique")
    for task in tasks:
        unknown = set(task["depends_on"]) - by_id.keys()
        if unknown:
            raise ValueError(f"{task['id']}: unknown dependencies: {', '.join(sorted(unknown))}")

    visiting = set()
    ranks = {}

    def rank(task_id):
        if task_id in visiting:
            raise ValueError(f"dependency cycle includes {task_id}")
        if task_id not in ranks:
            visiting.add(task_id)
            deps = by_id[task_id]["depends_on"]
            ranks[task_id] = 0 if not deps else 1 + max(rank(dep) for dep in deps)
            visiting.remove(task_id)
        return ranks[task_id]

    for task in tasks:
        task["rank"] = rank(task["id"])
    return tasks


def read_feature_metadata(feature_dir):
    feature_readme = feature_dir / "README.md"
    if not feature_readme.is_file():
        raise ValueError(f"{feature_readme}: feature README with id and title frontmatter is required")
    match = re.match(r"\A---\s*\n(.*?)\n---(?:\n|$)", feature_readme.read_text(encoding="utf-8"), re.S)
    if not match:
        raise ValueError(f"{feature_readme}: missing YAML frontmatter")
    fields = {}
    for line in match.group(1).splitlines():
        field = re.match(r"^(id|title):\s*(.*)$", line)
        if field:
            fields[field.group(1)] = scalar(field.group(2))
    if not fields.get("id") or not fields.get("title"):
        raise ValueError(f"{feature_readme}: frontmatter must include id and title")

    workspace_readme = feature_dir.parent.parent / "README.md"
    project_name = ""
    if workspace_readme.is_file():
        for line in workspace_readme.read_text(encoding="utf-8").splitlines():
            name = re.match(r"^Project name:\s*(.*?)\s*$", line, re.I)
            if name:
                project_name = scalar(name.group(1))
                break
    if not project_name or re.fullmatch(r"(?i)(?:<[^>]+>|(?:your\s+)?project(?:\s+name)?|tbd|unknown|todo)", project_name):
        raise ValueError(f"{workspace_readme}: add a display name as `Project name: <name>` (ask the human if unknown)")
    return project_name, fields["id"], fields["title"]


def dependency_map_layout(tasks):
    node_width, node_height, column_gap, row_gap, pad = 92, 36, 38, 12, 12
    stride_x, stride_y = node_width + column_gap, node_height + row_gap
    dependents = {dependency for task in tasks for dependency in task["depends_on"]}
    isolated = [task for task in tasks if not task["depends_on"] and task["id"] not in dependents]
    dag = [task for task in tasks if task not in isolated]
    isolated_columns = (len(isolated) + 2) // 3
    group_width = isolated_columns * node_width + max(0, isolated_columns - 1) * column_gap + 2 * pad
    dag_start = pad + group_width + column_gap if isolated else pad
    positions = {}

    for index, task in enumerate(isolated):
        positions[task["id"]] = {
            "x": pad + (index // 3) * stride_x,
            "y": 30 + pad + (index % 3) * stride_y,
        }

    ranks = {}
    for task in dag:
        ranks.setdefault(task["rank"], []).append(task)
    rank_starts = {}
    next_column = 0
    for rank in sorted(ranks):
        rank_starts[rank] = next_column
        next_column += (len(ranks[rank]) + 2) // 3
        for index, task in enumerate(ranks[rank]):
            positions[task["id"]] = {
                "x": dag_start + (rank_starts[rank] + index // 3) * stride_x,
                "y": pad + (index % 3) * stride_y,
            }

    graph_width = max((pos["x"] + node_width + pad for pos in positions.values()), default=300)
    graph_height = max((pos["y"] + node_height + pad for pos in positions.values()), default=88)
    group = None
    if isolated:
        rows = min(3, len(isolated))
        group = {
            "x": 6,
            "y": 6,
            "width": group_width - 2,
            "height": 30 + pad + rows * node_height + (rows - 1) * row_gap + pad,
        }
        graph_height = max(graph_height, group["height"] + 6)
    return {
        "nodes": positions,
        "isolated_ids": [task["id"] for task in isolated],
        "isolated_group": group,
        "width": graph_width,
        "height": graph_height,
    }


