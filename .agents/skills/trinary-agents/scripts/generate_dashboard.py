MARKER = "<!-- Generated by trinary-agents; do not edit. -->"
HANDOFF_NAME = re.compile(r"^(\d{8}_\d{6})--(?P<role>.+?)-handoff-(?P<sequence>\d+)\.md$")
HANDOFF_FIELD = re.compile(
    r"^\s*(?:-\s*)?(?:\*\*)?(Role|Recipient|Outcome|Decision|Timestamp(?: \([^)]*\))?|Created|From|To|Task)"
    r"(?::\*\*|\*\*:|:)\s*(.*?)\s*(?:\*\*)?\s*$",
    re.I,
)
HANDOFF_VERDICT = re.compile(r"^\s*(?:-\s*)?(?:\*\*)?VERDICT\s*:\s*(.*?)\s*(?:\*\*)?\s*$", re.I)
DASHBOARD_ASSETS = Path(__file__).resolve().parent.parent / "assets" / "dashboard"


